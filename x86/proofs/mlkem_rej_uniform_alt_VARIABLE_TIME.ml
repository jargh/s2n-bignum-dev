  ASM_REWRITE_TAC[DIMINDEX_CONV `dimindex(:12)`] THEN
  DISCH_THEN(fun th -> REWRITE_TAC[th]) THEN
  MP_TAC(ISPECL
   [`res:int64`; `val(n:int64)`; `2 * val(n:int64)`; `curlist:int16 list`]
