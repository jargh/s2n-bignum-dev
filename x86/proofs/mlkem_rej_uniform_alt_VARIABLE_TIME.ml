let REJ_CANDIDATES_GEN n =
  let ty = mk_word_ty(num(24 * n)) in
  let ch = mk_var("ch",ty) in
  let sw t = mk_const("word_subword",
               type_match (get_const_type "word_subword")
                 (mk_fun_ty ty (mk_fun_ty `:num#num` t)) []) in
  let byte k = mk_comb(mk_comb(sw `:byte`,ch),mk_pair(mk_small_numeral k,`8`))
  and fld j = mk_comb(`word_zx:(12)word->int16`,
                mk_comb(mk_comb(sw `:(12)word`,ch),
                        mk_pair(mk_small_numeral(12 * j),`12`))) in
  let jn a b = mk_comb(mk_comb(`word_join:byte->byte->int16`,a),b) in
  let cand j =
    let k = j / 2 in
    if j mod 2 = 0 then
      mk_comb(mk_comb(`word_and:int16->int16->int16`,
                      jn (byte(24 * k + 8)) (byte(24 * k))),`word 4095:int16`)
    else
      mk_comb(mk_comb(`word_ushr:int16->num->int16`,
                      jn (byte(24 * k + 16)) (byte(24 * k + 8))),`4`) in
  map (fun j -> GEN ch (BITBLAST_RULE (mk_eq(cand j,fld j)))) (0--(2*n-1));;

