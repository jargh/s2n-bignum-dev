              (word 0x0fff0fff0fff0fff0fff0fff0fff0fff:int128) /\
    read YMM12 s =
    word_join (word 0x0d800d800d800d800d800d800d800d80:int128)
              (word 0x0d800d800d800d800d800d800d800d80:int128) /\
