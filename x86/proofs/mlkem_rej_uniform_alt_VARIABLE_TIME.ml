let rej_fin = new_definition
 `rej_fin (res:int64) (buf:int64) buflen (table:int64) curlist inlist
          (stk:int64) (e:(uarch_event)list) (s:x86state) <=>
    ?q. 24 * q <= buflen /\
        (buflen < 24 * (q + 1) \/ 256 <= LENGTH(rej_out curlist inlist q)) /\
        rej_inv res buf buflen table curlist inlist stk e q s`;;

let REJ_FRAME_IDEMPOT = prove
 (`!res stk:int64.
     (MAYCHANGE [RSP] ,, MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
      MAYCHANGE [memory :> bytes(res,512); memory :> bytes(stk,32)]) ,,
     (MAYCHANGE [RSP] ,, MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
      MAYCHANGE [memory :> bytes(res,512); memory :> bytes(stk,32)]) =
     (MAYCHANGE [RSP] ,, MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
      MAYCHANGE [memory :> bytes(res,512); memory :> bytes(stk,32)])`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI] THEN
  MAYCHANGE_IDEMPOT_TAC);;

