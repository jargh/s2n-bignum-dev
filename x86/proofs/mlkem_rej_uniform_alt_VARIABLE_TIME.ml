  and hi1,hi0 = dest_binop `word_join:byte->byte->int16` hi in
  let bytes = if length names = 2 then [lo0; hi0] else [lo0; lo1; hi0; hi1] in
  MAP_EVERY (fun (n,t) -> ABBREV_TAC(mk_eq(mk_var(n,`:byte`),t)))
    (zip names bytes) (asl,w);;

