  let th = snd(find (fun (_,th) -> let c = concl th in
                       is_eq c && lhs c = rd) asl) in
  let th1 = CONV_RULE(RAND_CONV(REWRITE_CONV[REJ_MOD256; GSYM REJ_SHL4])) th in
  let eq = BITBLAST_RULE(mk_eq(rand(concl th1),target)) in
  (UNDISCH_THEN (concl th) (K ALL_TAC) THEN
   ASSUME_TAC(REWRITE_RULE[REJ_SHL4] (TRANS th1 eq))) (asl,w);;

let REJ_INDEX_TAC reg k m =
  REJ_REG_NORM_TAC reg k
   (vsubst [m,`m:byte`] `word_shl (word_zx (m:byte)) 4:int64`);;

let REJ_COUNT_TAC reg k m =
  REJ_REG_NORM_TAC reg k
   (vsubst [m,`m:byte`] `word (word_popcount (m:byte)):int64`);;

let VAL_BOUND_BYTE = prove
 (`!m:byte. val m < 256`,
  GEN_TAC THEN MP_TAC(ISPEC `m:byte` VAL_BOUND) THEN
  REWRITE_TAC[DIMINDEX_8] THEN ARITH_TAC);;

(*** The table entry for mask m at state k, abbreviated as name, and its
 *** value as an element of the table
 ***)

let REJ_TAB_TAC name m k (asl,w) =
  let sv = mk_var("s"^string_of_int k,`:x86state`) in
  let rd = subst [m,`m:byte`; sv,`s:x86state`]
   `read (memory :> bytes128 (word_add table (word(16 * val(m:byte))))) s` in
  let v = mk_var(name,`:int128`) in
  let tpat = subst [sv,`s:x86state`]
    `read (memory :> bytes(table,4096)) s =
     num_of_wordlist mlkem_rej_uniform_table` in
  let tth = snd(find (fun (_,th) -> concl th = tpat) asl) in
  let lth = MP (SPECL [`table:int64`; sv; mk_comb(`val:byte->num`,m)]
                 REJ_TABLE_LOOKUP)
               (CONJ tth (ISPEC m VAL_BOUND_BYTE)) in
  (ABBREV_TAC(mk_eq(v,rd)) THEN
   FIRST_ASSUM(fun ath -> if concl ath = mk_eq(rd,v)
     then ASSUME_TAC(TRANS (SYM ath) lth) else NO_TAC) THEN
   ASSUME_TAC(ISPEC m VAL_BOUND_BYTE)) (asl,w);;

(*** The compaction of a group of 8 candidates by vpshufb with the table
 *** entry for their mask, as the accepted candidates, and their number as
 *** the popcount of the mask, checked for all 256 masks. The lookup in a
 *** lane is in the form it has in the simulation.
 ***)

let VPSHUFB_EXPANDED =
  let th = (REWRITE_CONV all_simd_rules THENC DEPTH_CONV DIMINDEX_CONV THENC
            TOP_DEPTH_CONV WORD_SIMPLE_SUBWORD_CONV)
           `usimd16 (\i. if bit 7 i then word 0
                         else word_subword (v:int128)
                               (8 * val(word_subword i (0,4):nybble),8):byte)
                    (m:int128)` in
  rand(concl th);;

let REJ_VAL_ZX12 = prove
 (`!d:12 word. val(word_zx d:int16) = val d`,
  GEN_TAC THEN MATCH_MP_TAC VAL_WORD_ZX THEN
  REWRITE_TAC[DIMINDEX_16; DIMINDEX_CONV `dimindex(:12)`] THEN ARITH_TAC);;

let REJ_GROUP_X86 =
  let ds = map (fun i -> mk_var("d"^string_of_int i,`:12 word`)) (0--7) in
  let cs = map (fun d -> mk_comb(`word_zx:12 word->int16`,d)) ds in
  let bits = map (fun d -> mk_comb(`word:num->1 word`,
                    mk_comb(`bitval`,mk_binop `(<):num->num->bool`
                      (mk_comb(`val:12 word->num`,d)) `3329`))) ds in
  let msk = mk_jointree bits in
  let v = mk_jointree cs in
  let lhs = subst [v,`v:int128`; `tab:int128`,`m:int128`] VPSHUFB_EXPANDED in
  let flt = mk_comb(`FILTER (\x:int16. val x < 3329)`,mk_list(cs,`:int16`)) in
  let stm =
    list_mk_forall(ds @ [`tab:int128`],
     mk_imp(mk_eq(`tab:int128`,
              mk_comb(mk_comb(`EL:num->int128 list->int128`,
                              mk_comb(`val:byte->num`,msk)),
                      `REJ_ENTRIES`)),
            mk_conj(mk_eq(lhs,mk_comb(`rej_pack`,flt)),
                    mk_eq(mk_comb(`word_popcount:byte->num`,msk),
                          mk_comb(`LENGTH:int16 list->num`,flt))))) in
  prove
   (stm,
    REPEAT GEN_TAC THEN DISCH_THEN SUBST1_TAC THEN
    REWRITE_TAC[FILTER; REJ_VAL_ZX12] THEN
    MAP_EVERY (fun d -> ASM_CASES_TAC(subst [d,`d:12 word`]
                                       `val(d:12 word) < 3329`)) ds THEN
    ASM_REWRITE_TAC[BITVAL_CLAUSES; rej_pack; LENGTH] THEN
    CONV_TAC(DEPTH_CONV WORD_RED_CONV) THEN
    REWRITE_TAC[REJ_ENTRIES] THEN CONV_TAC(ONCE_DEPTH_CONV EL_CONV) THEN
    CONV_TAC(DEPTH_CONV WORD_RED_CONV THENC NUM_REDUCE_CONV) THEN
    CONV_TAC(TOP_DEPTH_CONV
     (WORD_SIMPLE_SUBWORD_CONV ORELSEC WORD_SUBWORD_BEYOND_CONV)) THEN
    CONV_TAC WORD_BLAST);;

(*** The compaction by vpshufb of the two lanes of register reg at state k
 *** (whose table entries the simulation has written as the elements of the
 *** table for the masks) as the packed accepted candidates, and the counts
 ***)

let REJ_GROUP_TAC reg k (asl,w) =
  let sv = mk_var("s"^string_of_int k,`:x86state`) in
  let rd = mk_comb(mk_comb(`read:(x86state,int256)component->x86state->int256`,
                           reg),sv) in
  let qth = snd(find (fun (_,th) -> let c = concl th in
                        is_eq c && lhs c = rd) asl) in
  let hi,lo =
    dest_binop `word_join:int128->int128->int256` (rand(concl qth)) in
  let rec leaves t =
    match t with
      Comb(Comb(Const("word_join",_),a),b) -> leaves b @ leaves a
    | _ -> [t] in
  let lane l =
    let _,ins,_ = term_match [] VPSHUFB_EXPANDED l in
    let vv = rev_assoc `v:int128` ins and tab = rev_assoc `m:int128` ins in
    let ds = map rand (leaves vv) in
    let gth = SPECL (ds @ [tab]) REJ_GROUP_X86 in
    let ant = lhand(concl gth) in
    let msk = rand(lhand(rand ant)) in
    let mv = rand(lhand tab) in
    let mth = snd(find (fun (_,th) -> concl th = mk_eq(msk,mv)) asl) in
    let r1,r2 = CONJ_PAIR(MP gth (SYM(CONV_RULE(BINOP_CONV BETA_CONV)
                  (AP_TERM `\m:byte. EL (val m) REJ_ENTRIES` mth)))) in
    r1,REWRITE_RULE[mth] r2 in
  let lo1,lo2 = lane lo and hi1,hi2 = lane hi in
  let nth = CONV_RULE(RAND_CONV(BINOP_CONV(REWRITE_CONV[lo1; hi1])))
              qth in
  (UNDISCH_THEN (concl qth) (K ALL_TAC) THEN
   ASSUME_TAC(REWRITE_RULE[REJ_PACK] nth) THEN
   ASSUME_TAC lo2 THEN ASSUME_TAC hi2) (asl,w);;

(*** Abbreviate t as v, also in all the assumptions ***)

let ABBREV_EVERYWHERE_TAC tm =
  let v,t = dest_eq tm in
  ABBREV_TAC tm THEN
  FIRST_ASSUM(fun th ->
    if concl th = mk_eq(t,v) then
      RULE_ASSUM_TAC(fun th' ->
        if concl th' = concl th then th' else REWRITE_RULE[th] th')
    else NO_TAC);;

let LENGTH_FILTER_8 = prove
 (`!P (a0:A) a1 a2 a3 a4 a5 a6 a7.
        LENGTH(FILTER P [a0;a1;a2;a3;a4;a5;a6;a7]) <= 8`,
  REPEAT GEN_TAC THEN
  W(MP_TAC o PART_MATCH lhand LENGTH_FILTER o lhand o snd) THEN
  REWRITE_TAC[LENGTH] THEN ARITH_TAC);;

(*** Abbreviate the lists in the lanes of the compacted register reg at
 *** state k, word(num_of_wordlist l), as the given names, and their
 *** lengths (with their bounds), and the counts in the registers
 ***)

let REJ_LIST_ABBREV_TAC reg k names lens (asl,w) =
  let sv = mk_var("s"^string_of_int k,`:x86state`) in
  let rd = mk_comb(mk_comb(`read:(x86state,int256)component->x86state->int256`,
                           reg),sv) in
  let qth = snd(find (fun (_,th) -> let c = concl th in
                        is_eq c && lhs c = rd) asl) in
  let hi,lo =
    dest_binop `word_join:int128->int128->int256` (rand(concl qth)) in
  let ls = [rand(rand lo); rand(rand hi)] in
  let tacs = map2 (fun (l,n) len ->
    let lv = mk_var(n,`:int16 list`) in
    let lth = PART_MATCH lhand LENGTH_FILTER_8
                (mk_comb(`LENGTH:int16 list->num`,l)) in
    ASSUME_TAC lth THEN
    ABBREV_EVERYWHERE_TAC (mk_eq(lv,l)) THEN
    ABBREV_EVERYWHERE_TAC (mk_eq(mk_var(len,`:num`),
                                 mk_comb(`LENGTH:int16 list->num`,lv))))
    (zip ls names) lens in
  EVERY tacs (asl,w);;

(*** Rewrite the other assumptions with the counts `word_popcount m = n` ***)

let REJ_COUNTS_TAC (asl,w) =
  let cs = map snd (filter (fun (_,th) -> can (term_match []
             `word_popcount(m:byte) = n`) (concl th)) asl) in
  RULE_ASSUM_TAC(fun th ->
    if mem (concl th) (map concl cs) then th else REWRITE_RULE cs th) (asl,w);;

(*** Storing the 16 bytes of a group extends the result in memory ***)

let REJ_STORE_AT_TAC a (asl,w) =
  let spat = subst [a,`a:int64`]
   `read (memory :> bytes128 (word_add a (word(2 * n))))
         (s:x86state) = word(num_of_wordlist (l:int16 list))` in
  let sth =
    snd(find (fun (_,th) -> can (term_match [a] spat) (concl th)) asl) in
  let _,ins,_ = term_match [a] spat (concl sth) in
  let n = rev_assoc `n:num` ins and s = rev_assoc `s:x86state` ins
  and l = rev_assoc `l:int16 list` ins in
  let mpat = subst [a,`a:int64`; n,`n:num`; s,`s:x86state`]
    `read (memory :> bytes(a,2 * n)) s = num_of_wordlist (L:int16 list)` in
  let mth =
    snd(find (fun (_,th) -> can (term_match [a] mpat) (concl th)) asl) in
  let bigl = rand(rand(concl mth)) in
  (MP_TAC(SPECL [a; n; bigl; l; s] REJ_STORE) THEN
   ANTS_TAC THENL [ASM_REWRITE_TAC[LENGTH_APPEND]; DISCH_TAC]) (asl,w);;

let REJ_STORE_TAC = REJ_STORE_AT_TAC `res:int64`;;

let REJ_STORE_LEN_TAC =
  REJ_STORE_TAC THEN
  W(fun (asl,w) ->
    let lens = filter (fun (_,th) ->
      can (term_match [] `LENGTH(l:int16 list) = n`) (concl th)) asl in
    POP_ASSUM(MP_TAC o REWRITE_RULE (map snd lens)) THEN DISCH_TAC);;

(*** The low lane of a register, and the output pointer after a group ***)

let REJ_ZX_JOIN = BITBLAST_RULE
 `!h l:int128. word_zx (word_join h l:int256):int128 = l`;;

let REJ_ADDR_NORM = prove
 (`!c l. l < 2 EXP 64 ==> 2 * c + 2 * val(word l:int64) = 2 * (c + l)`,
  SIMP_TAC[VAL_WORD; DIMINDEX_64; MOD_LT] THEN ARITH_TAC);;

(*** Prove REJ_SAMPLE(SUB_LIST(m,n) inlist) = APPEND lis0 (...) for the
 *** abbreviated groups lis, using the instances for j < k of the chunk
 *** facts !j. j < k ==> EL (... + j) inlist = word_subword ch (12 * j,12)
 *** in the assumptions with the given labels, and the given facts for the
 *** length of the input
 ***)

let REJ_SAMPLE_EXPAND_TAC expth lis labs lenfacts =
  let inst th =
    let k = dest_small_numeral(rand(lhand(snd(dest_forall(concl th))))) in
    map (fun j ->
      CONV_RULE (NUM_REDUCE_CONV THENC REWRITE_CONV[ADD_CLAUSES])
       (MP (SPEC (mk_small_numeral j) th)
           (EQT_ELIM(NUM_REDUCE_CONV
              (mk_binop `(<):num->num->bool` (mk_small_numeral j)
                        (mk_small_numeral k))))))
      (0--(k-1)) in
  MAP_EVERY EXPAND_TAC lis THEN
  REWRITE_TAC[GSYM APPEND_ASSOC; GSYM FILTER_APPEND; APPEND; REJ_SAMPLE] THEN
  AP_TERM_TAC THEN
  W(fun (asl,w) ->
    let t = find_term (fun t ->
      match t with
        Comb(Comb(Const("SUB_LIST",_),Comb(Comb(Const(",",_),_),_)),_) -> true
      | _ -> false) w in
    MP_TAC(PART_MATCH (lhand o rand) expth t) THEN
    ANTS_TAC THENL
     [MAP_EVERY UNDISCH_TAC lenfacts THEN ARITH_TAC;
      DISCH_THEN SUBST1_TAC]) THEN
  REWRITE_TAC[MAP; GSYM ADD_ASSOC] THEN CONV_TAC(DEPTH_CONV NUM_ADD_CONV) THEN
  MAP_EVERY (fun l -> USE_THEN l (fun th -> REWRITE_TAC(inst th))) labs;;

