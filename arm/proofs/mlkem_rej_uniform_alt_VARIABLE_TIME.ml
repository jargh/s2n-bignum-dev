(* The de-interleaving by ld3 *)

let LD3_TAC =
  RULE_ASSUM_TAC(fun th ->
    if can (term_match [] `read (Q:(armstate,int128)component) s =
                            word_zx(word_subdeinterleave 3 8 x j:int64)`)
           (concl th) ||
       can (term_match [] `read (Q:(armstate,int128)component) s =
