(* ------------------------------------------------------------------------- *)
(* The selection of the accepted candidates of a group of 8, checked for all *)
(* 256 masks. Lane j of the masks is weighted by 2^j + 2^8, so the sum of a  *)
(* group is the table index plus 2^8 times the number accepted.              *)
(* ------------------------------------------------------------------------- *)

let rej_mask = new_definition
 `rej_mask (w:int16) (c:int16) =
  word_and w (word_neg(word(bitval(word_ugt (word 3329) c))))`;;

let rej_gsum = new_definition
 `rej_gsum (c0:int16) c1 c2 c3 c4 c5 c6 c7 =
  word_add
   (word_add
     (word_add (rej_mask (word 257) c0) (rej_mask (word 258) c1))
     (word_add (rej_mask (word 260) c2) (rej_mask (word 264) c3)))
   (word_add
     (word_add (rej_mask (word 272) c4) (rej_mask (word 288) c5))
     (word_add (rej_mask (word 320) c6) (rej_mask (word 384) c7)))`;;

let rej_pack = define
 `rej_pack ([]:int16 list) = (word 0:int128) /\
  rej_pack (CONS h t) = word_or (word_zx h) (word_shl (rej_pack t) 16)`;;

let REJ_PACK = prove
 (`!l:int16 list. rej_pack l = word(num_of_wordlist l)`,
  LIST_INDUCT_TAC THEN
  ASM_REWRITE_TAC[rej_pack; num_of_wordlist; DIMINDEX_16] THEN
  SPEC_TAC(`num_of_wordlist(t:int16 list)`,`n:num`) THEN GEN_TAC THEN
  MP_TAC(INST [`word n:int128`,`x:int128`] (BITBLAST_RULE
    `word_or (word_zx (h:int16)) (word_shl (x:int128) 16) =
     word_add (word_zx h) (word_shl x 16)`)) THEN
  REWRITE_TAC[word_zx; WORD_SHL_WORD; GSYM WORD_ADD] THEN
  DISCH_THEN ACCEPT_TAC);;

let WORD_UGT_3329 = prove
 (`!c:int16. word_ugt (word 3329) c <=> val c < 3329`,
  REWRITE_TAC[WORD_UGT; VAL_WORD; DIMINDEX_16] THEN
  CONV_TAC NUM_REDUCE_CONV THEN ARITH_TAC);;

(* The table lookup (tbl) with the table entry m, expanded as in the code. *)

let TBL_EXPANDED =
  let th = (REWRITE_CONV all_simd_rules THENC DEPTH_CONV DIMINDEX_CONV THENC
            TOP_DEPTH_CONV WORD_SIMPLE_SUBWORD_CONV)
           `usimd16 (\x. word_subword (v:int128) (8 * val x,8):byte)
                    (m:int128)` in
  rand(concl th);;

let REJ_GROUP =
  let cs = map (fun i -> mk_var("c"^string_of_int i,`:int16`)) (0--7) in
  let rec jn l =
    match l with
      [x] -> x
    | _ -> let lo,hi = chop_list (length l / 2) l in
           let a = jn hi and b = jn lo in
           let ty = mk_word_ty(num(16 * length l)) in
           let c = mk_const("word_join",type_match
                     (get_const_type "word_join")
                     (mk_fun_ty (type_of a) (mk_fun_ty (type_of b) ty)) []) in
           mk_comb(mk_comb(c,a),b) in
  let lhs = subst [jn cs,`v:int128`; `tab:int128`,`m:int128`] TBL_EXPANDED in
  let flt = mk_comb(`FILTER (\x:int16. val x < 3329)`,mk_list(cs,`:int16`)) in
  let gs = list_mk_comb(`rej_gsum`,cs) in
  let idx = mk_comb(`val:byte->num`,
              mk_comb(mk_comb(`word_subword:int16->num#num->byte`,gs),
                      `(0,8)`)) in
  let cnt = mk_comb(`val:(4)word->num`,
              mk_comb(mk_comb(`word_subword:int16->num#num->(4)word`,gs),
                      `(8,4)`)) in
  let stm =
    list_mk_forall(cs @ [`tab:int128`],
     mk_imp(mk_eq(`tab:int128`,
              mk_comb(mk_comb(`EL:num->int128 list->int128`,idx),
                      `REJ_ENTRIES`)),
            mk_conj(mk_eq(lhs,mk_comb(`rej_pack`,flt)),
                    mk_eq(cnt,mk_comb(`LENGTH:int16 list->num`,flt))))) in
  prove
   (stm,
    REPEAT GEN_TAC THEN DISCH_THEN SUBST1_TAC THEN
    REWRITE_TAC[rej_gsum; rej_mask; WORD_UGT_3329; FILTER] THEN
    MAP_EVERY (fun c -> ASM_CASES_TAC(subst [c,`c:int16`]
                                       `val(c:int16) < 3329`)) cs THEN
    ASM_REWRITE_TAC[BITVAL_CLAUSES; rej_pack; LENGTH] THEN
    CONV_TAC(DEPTH_CONV WORD_RED_CONV) THEN
    REWRITE_TAC[REJ_ENTRIES] THEN CONV_TAC(ONCE_DEPTH_CONV EL_CONV) THEN
    CONV_TAC(DEPTH_CONV WORD_RED_CONV THENC NUM_REDUCE_CONV) THEN
    CONV_TAC(TOP_DEPTH_CONV
     (WORD_SIMPLE_SUBWORD_CONV ORELSEC WORD_SUBWORD_BEYOND_CONV)) THEN
    CONV_TAC WORD_BLAST);;

