(* The expansion of SUB_LIST(m,n) l into elements, for a numeral n. *)

let SUB_LIST_EXPAND_RULE n =
  let l = `l:A list` and m = `m:num` in
  let el k = mk_comb(mk_comb(`EL:num->A list->A`,
               if k = 0 then m
               else mk_binop `(+):num->num->num` m (mk_small_numeral k)),l) in
  let tm = list_mk_forall([l;m],
    mk_imp(mk_binop `(<=):num->num->bool`
             (mk_binop `(+):num->num->num` m (mk_small_numeral n))
             (mk_comb(`LENGTH:A list->num`,l)),
           mk_eq(mk_comb(mk_comb(`SUB_LIST:num#num->A list->A list`,
                   mk_pair(m,mk_small_numeral n)),l),
                 mk_list(map el (0--(n-1)),`:A`)))) in
  let is_sub_list t =
    match t with
      Comb(Comb(Const("SUB_LIST",_),Comb(Comb(Const(",",_),_),_)),_) -> true
    | _ -> false in
  let step_conv t =
    if is_sub_list t &&
       let k = rand(lhand t) in is_numeral k && dest_small_numeral k > 0
    then LAND_CONV(RAND_CONV num_CONV) t else failwith "step_conv" in
  prove(tm,
    REPEAT STRIP_TAC THEN
    REPEAT(CONV_TAC(ONCE_DEPTH_CONV step_conv) THEN
      W(fun (asl,w) ->
        let is_suc t = match t with
            Comb(Const("SUC",_),_) -> true | _ -> false in
        let t = find_term
          (fun t -> is_sub_list t && is_suc(rand(lhand t))) w in
        MP_TAC(PART_MATCH (lhand o rand) SUB_LIST_CONS_EL t) THEN
        ANTS_TAC THENL [ASM_ARITH_TAC; DISCH_THEN SUBST1_TAC])) THEN
    REWRITE_TAC[SUB_LIST_CLAUSES; CONS_11; GSYM ADD_ASSOC] THEN
    CONV_TAC(DEPTH_CONV NUM_ADD_CONV) THEN REWRITE_TAC[ADD_CLAUSES]);;

let SUB_LIST_EXPAND_16 = SUB_LIST_EXPAND_RULE 16;;

let SUB_LIST_EXPAND_32 = SUB_LIST_EXPAND_RULE 32;;

let SUB_LIST_EXPAND_64 = SUB_LIST_EXPAND_RULE 64;;

