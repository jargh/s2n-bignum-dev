(* Simplification of subwords in the latest or all scalar registers *)

let SCALAR_SIMPLIFY_TAC =
  TRY(FIRST_X_ASSUM
   (ASSUME_TAC o
    CONV_RULE(RAND_CONV(TOP_DEPTH_CONV WORD_SIMPLE_SUBWORD_CONV)) o
    check (can (term_match [] `read X (s:armstate):int64 = whatever`) o
           concl)));;

let SCALAR_SIMPLIFY_ALL_TAC =
  RULE_ASSUM_TAC(fun th ->
    if can (term_match [] `read X (s:armstate):int64 = whatever`) (concl th)
    then CONV_RULE(RAND_CONV(TOP_DEPTH_CONV WORD_SIMPLE_SUBWORD_CONV)) th
    else th);;

(* The table entry loaded with index register reg, abbreviated as name, *)
(* and its value as an element of the table, with the bound on the      *)
(* index used for the bounds check of the load.                         *)

let VAL_SUBWORD_08 = prove
 (`!g:int16. val(word_subword g (0,8):int64) = val(word_subword g (0,8):byte)`,
  REWRITE_TAC[VAL_WORD_SUBWORD; DIMINDEX_64; DIMINDEX_8] THEN
  CONV_TAC NUM_REDUCE_CONV);;

let VAL_SUBWORD_08_BOUND = prove
 (`!g:int16. val(word_subword g (0,8):int64) < 256`,
  REWRITE_TAC[VAL_WORD_SUBWORD; DIMINDEX_64] THEN CONV_TAC NUM_REDUCE_CONV THEN
  REWRITE_TAC[MOD_LT_EQ] THEN ARITH_TAC);;

let TABLE_ABBREV_TAC name reg (asl,w) =
  let th = snd(find (fun (_,th) ->
    let t = concl th in
    is_eq t && is_comb(lhs t) &&
    (match lhs t with Comb(Comb(Const("read",_),r),_) -> r = reg | _ -> false))
    asl) in
  let v = rand(concl th) and s = rand(lhs(concl th)) in
  let rd = subst [v,`v:int64`; s,`s:armstate`]
    `read (memory :> bytes128 (word_add table (word(16 * val(v:int64))))) s` in
  ABBREV_TAC(mk_eq(mk_var(name,`:int128`),rd)) (asl,w);;

let TAB_LOOKUP_TAC tab (asl,w) =
  let pat = `read (memory :> bytes128
                   (word_add table (word(16 * val(v:int64))))) (s:armstate) =
             (t:int128)` in
  let ath = snd(find (fun (_,th) ->
    let c = concl th in is_eq c && rand c = tab && can (term_match [] pat) c)
    asl) in
  let _,ins,_ = term_match [] pat (concl ath) in
  let v = rev_assoc `v:int64` ins and s = rev_assoc `s:armstate` ins in
  let g = rand(rator v) in
  let tpat = subst [s,`s:armstate`]
    `read (memory :> bytes(table,4096)) s =
     num_of_wordlist mlkem_rej_uniform_table` in
  let tth = snd(find (fun (_,th) -> concl th = tpat) asl) in
  let lth = SPECL [`table:int64`; s; mk_comb(`val:int64->num`,v)]
              REJ_TABLE_LOOKUP in
  let ith = MP lth (CONJ tth (ISPEC g VAL_SUBWORD_08_BOUND)) in
  let fth = REWRITE_RULE[VAL_SUBWORD_08] (TRANS (SYM ath) ith) in
  (ASSUME_TAC fth THEN ASSUME_TAC(ISPEC g VAL_SUBWORD_08_BOUND)) (asl,w);;

(* The result of tbl on a group, as the packed accepted candidates, and *)
(* the count fact about the group.                                      *)

let GROUP_APPLY_TAC q (asl,w) =
  let isreg c = is_eq c &&
    (match lhs c with Comb(Comb(Const("read",_),r),_) -> r = q | _ -> false) in
  let qth = snd(find (fun (_,th) -> isreg(concl th)) asl) in
  let _,ins,_ = term_match [] TBL_EXPANDED (rand(concl qth)) in
  let vv = rev_assoc `v:int128` ins and tab = rev_assoc `m:int128` ins in
  let rec leaves t =
    match t with
      Comb(Comb(Const("word_join",_),a),b) -> leaves b @ leaves a
    | _ -> [t] in
  let cs = leaves vv in
  let gth = SPECL (cs @ [tab]) REJ_GROUP in
  let ant = lhand(concl gth) in
  let lth =
    if lhand ant = rand ant then REFL (lhand ant)
    else snd(find (fun (_,th) -> concl th = ant) asl) in
  let r1,r2 = CONJ_PAIR(MP gth lth) in
  (UNDISCH_THEN (concl qth) (K ALL_TAC) THEN
   ASSUME_TAC(TRANS qth r1) THEN ASSUME_TAC r2) (asl,w);;

let SUBWORD_84_AS_WORD = prove
 (`!g:int16. word_subword g (8,4):int64 =
             word(val(word_subword g (8,4):(4)word))`,
  GEN_TAC THEN REWRITE_TAC[GSYM VAL_EQ; VAL_WORD; VAL_WORD_SUBWORD] THEN
  REWRITE_TAC[DIMINDEX_64; DIMINDEX_CONV `dimindex(:4)`] THEN
  CONV_TAC NUM_REDUCE_CONV THEN REWRITE_TAC[MOD_MOD_REFL] THEN
  MATCH_MP_TAC(GSYM MOD_LT) THEN
  TRANS_TAC LTE_TRANS `16` THEN REWRITE_TAC[MOD_LT_EQ] THEN ARITH_TAC);;

let LENGTH_FILTER_8 = prove
 (`!P (a0:A) a1 a2 a3 a4 a5 a6 a7.
        LENGTH(FILTER P [a0;a1;a2;a3;a4;a5;a6;a7]) <= 8`,
  REPEAT GEN_TAC THEN
  W(MP_TAC o PART_MATCH lhand LENGTH_FILTER o lhand o snd) THEN
  REWRITE_TAC[LENGTH] THEN ARITH_TAC);;

(* Abbreviate t as v, also in all the assumptions *)

let ABBREV_EVERYWHERE_TAC tm =
  let v,t = dest_eq tm in
  ABBREV_TAC tm THEN
  FIRST_ASSUM(fun th ->
    if concl th = mk_eq(t,v) then
      RULE_ASSUM_TAC(fun th' ->
        if concl th' = concl th then th' else REWRITE_RULE[th] th')
    else NO_TAC);;

(* Abbreviate the list in `read q s = word(num_of_wordlist l)` as lis and *)
(* its length as len, with the bound on the length.                     *)

let GROUP_ABBREV_TAC q lis len (asl,w) =
  let isreg c = is_eq c &&
    (match lhs c with Comb(Comb(Const("read",_),r),_) -> r = q | _ -> false) in
  let qth = snd(find (fun (_,th) -> isreg(concl th)) asl) in
  let l = rand(rand(concl qth)) in
  let lv = mk_var(lis,`:int16 list`) in
  let lth = PART_MATCH lhand LENGTH_FILTER_8
              (mk_comb(`LENGTH:int16 list->num`,l)) in
  (ASSUME_TAC lth THEN
   ABBREV_EVERYWHERE_TAC (mk_eq(lv,l)) THEN
   ABBREV_EVERYWHERE_TAC (mk_eq(mk_var(len,`:num`),
                                mk_comb(`LENGTH:int16 list->num`,lv))))
  (asl,w);;

(* Rewrite all other assumptions with the assumption `val(...) = v`, for *)
(* the given variable v, i.e. the count of a group.                      *)

let REWRITE_COUNT_TAC v =
  FIRST_ASSUM(fun c ->
    if is_eq(concl c) && rand(concl c) = v &&
       can (term_match [] `val(word_subword (g:int16) (8,4):(4)word)`)
           (lhand(concl c))
    then RULE_ASSUM_TAC(fun th ->
           if concl th = concl c then th else REWRITE_RULE[c] th)
    else NO_TAC);;

(* The output pointer after a group *)

let REJ_ADDR_STEP = prove
 (`!a:int64 c l.
        word_add (word_add a (word(2 * c))) (word_shl (word l) 1) =
        word_add a (word(2 * (c + l)))`,
  REWRITE_TAC[WORD_SHL_WORD; GSYM WORD_ADD_ASSOC; GSYM WORD_ADD] THEN
  REPEAT GEN_TAC THEN AP_TERM_TAC THEN AP_TERM_TAC THEN ARITH_TAC);;

(* The extension of the result in memory at a by the latest store of a  *)
(* group at a + 2 * n, given the result up to there.                    *)

let REJ_STORE_AT_TAC a (asl,w) =
  let spat = subst [a,`a:int64`]
   `read (memory :> bytes128 (word_add a (word(2 * n))))
         (s:armstate) = word(num_of_wordlist (l:int16 list))` in
  let sth =
    snd(find (fun (_,th) -> can (term_match [a] spat) (concl th)) asl) in
  let _,ins,_ = term_match [a] spat (concl sth) in
  let n = rev_assoc `n:num` ins and s = rev_assoc `s:armstate` ins
  and l = rev_assoc `l:int16 list` ins in
  let mpat = subst [a,`a:int64`; n,`n:num`; s,`s:armstate`]
    `read (memory :> bytes(a,2 * n)) s = num_of_wordlist (L:int16 list)` in
  let mth =
    snd(find (fun (_,th) -> can (term_match [a] mpat) (concl th)) asl) in
  let bigl = rand(rand(concl mth)) in
  (MP_TAC(SPECL [a; n; bigl; l; s] REJ_STORE) THEN
   ANTS_TAC THENL [ASM_REWRITE_TAC[LENGTH_APPEND]; DISCH_TAC]) (asl,w);;

let REJ_STORE_TAC = REJ_STORE_AT_TAC `res:int64`;;

(* Prove REJ_SAMPLE(SUB_LIST(m,n) inlist) = APPEND lis0 (...) for the *)
(* abbreviated groups lis, using the instances for j < k of the chunk  *)
(* facts !j. j < k ==> EL (... + j) inlist = word_subword ch (12 * j,12) *)
(* in the assumptions with the given labels, and the given facts for   *)
(* the length of the input.                                            *)

let REJ_SAMPLE_EXPAND_TAC expth lis labs lenfacts =
  let inst th =
    let k = dest_small_numeral(rand(lhand(snd(dest_forall(concl th))))) in
    map (fun j ->
      CONV_RULE (NUM_REDUCE_CONV THENC REWRITE_CONV[ADD_CLAUSES])
       (MP (SPEC (mk_small_numeral j) th)
           (EQT_ELIM(NUM_REDUCE_CONV
              (mk_binop `(<):num->num->bool` (mk_small_numeral j)
                        (mk_small_numeral k))))))
      (0--(k-1)) in
  MAP_EVERY EXPAND_TAC lis THEN
  REWRITE_TAC[GSYM APPEND_ASSOC; GSYM FILTER_APPEND; APPEND; REJ_SAMPLE] THEN
  AP_TERM_TAC THEN
  W(fun (asl,w) ->
    let t = find_term (fun t ->
      match t with
        Comb(Comb(Const("SUB_LIST",_),Comb(Comb(Const(",",_),_),_)),_) -> true
      | _ -> false) w in
    MP_TAC(PART_MATCH (lhand o rand) expth t) THEN
    ANTS_TAC THENL
     [MAP_EVERY UNDISCH_TAC lenfacts THEN ARITH_TAC;
      DISCH_THEN SUBST1_TAC]) THEN
  REWRITE_TAC[MAP; GSYM ADD_ASSOC] THEN CONV_TAC(DEPTH_CONV NUM_ADD_CONV) THEN
  MAP_EVERY (fun l -> USE_THEN l (fun th -> REWRITE_TAC(inst th))) labs;;

