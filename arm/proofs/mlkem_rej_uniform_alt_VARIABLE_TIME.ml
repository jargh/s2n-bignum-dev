let rej_fin = new_definition
 `rej_fin (res:int64) (buf:int64) buflen (table:int64) curlist inlist
          (stackpointer:int64) (e:(uarch_event)list) (s:armstate) <=>
    ?q. 24 * q <= buflen /\
        (buflen < 24 * (q + 1) \/ 256 <= LENGTH(rej_out curlist inlist q)) /\
        rej_inv res buf buflen table curlist inlist stackpointer e q s`;;

let REJ_FRAME_IDEMPOT = prove
 (`!res stackpointer:int64.
     (MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
      MAYCHANGE [memory :> bytes(res,512);
                 memory :> bytes(stackpointer,48)]) ,,
     (MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
      MAYCHANGE [memory :> bytes(res,512);
                 memory :> bytes(stackpointer,48)]) =
     (MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
      MAYCHANGE [memory :> bytes(res,512);
                 memory :> bytes(stackpointer,48)])`,
  REPEAT GEN_TAC THEN
  REWRITE_TAC[MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI] THEN
  MAYCHANGE_IDEMPOT_TAC);;

let REJ_TRANS = prove
 (`!res stackpointer:int64 (P:armstate->bool) Q R.
     ensures arm P Q
      (MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
       MAYCHANGE [memory :> bytes(res,512);
                  memory :> bytes(stackpointer,48)]) /\
     ensures arm Q R
      (MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
       MAYCHANGE [memory :> bytes(res,512);
                  memory :> bytes(stackpointer,48)])
     ==> ensures arm P R
          (MAYCHANGE_REGS_AND_FLAGS_PERMITTED_BY_ABI ,,
           MAYCHANGE [memory :> bytes(res,512);
                      memory :> bytes(stackpointer,48)])`,
  REPEAT STRIP_TAC THEN MATCH_MP_TAC ENSURES_TRANS_SIMPLE THEN
  EXISTS_TAC `Q:armstate->bool` THEN ASM_REWRITE_TAC[REJ_FRAME_IDEMPOT]);;

(* The precondition or postcondition at offset off with the state for p *)

let rej_at off p =
  subst [mk_small_numeral off,`off:num`; p,`p:num`]
   `\s. aligned_bytes_loaded s (word pc) mlkem_rej_uniform_alt_tmc /\
        read PC s = word(pc + off) /\
        rej_inv res buf buflen table curlist inlist stackpointer e p s`;;

let REJ_AT_TAC off p = EXISTS_TAC (rej_at off p);;

let REJ_EXIT_FIN_TAC =
  MATCH_MP_TAC ENSURES_POSTCONDITION_THM THEN
  REJ_AT_TAC 0x3c4 `p:num` THEN CONJ_TAC THENL
   [BETA_TAC THEN REWRITE_TAC[rej_fin] THEN REPEAT STRIP_TAC THEN
    ASM_REWRITE_TAC[] THEN EXISTS_TAC `p:num` THEN ASM_REWRITE_TAC[] THEN
    ASM_ARITH_TAC;
    MATCH_MP_TAC REJ_LOOP24_EXIT THEN ASM_ARITH_TAC];;

