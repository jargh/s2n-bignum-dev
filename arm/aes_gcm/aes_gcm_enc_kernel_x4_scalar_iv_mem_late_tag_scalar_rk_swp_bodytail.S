// ----------------------------------------------------------------------------
// AES-GCM encryption kernel (AES-128), SLOTHY software-pipelined main loop with
// body-only tail: x4_scalar_iv_mem_late_tag_scalar_rk_swp_bodytail
// Encrypts the input in CTR mode while accumulating the GHASH of the output.

// extern uint64_t aes_gcm_enc_kernel_x4_scalar_iv_mem_late_tag_scalar_rk_swp_bodytail(const uint8_t *in, uint64_t len_bits,
// uint8_t *out, uint64_t *tag,
// const uint8_t *ivec,
// const s2n_bignum_AES_KEY *key,
// const uint64_t *Htable);

// Processes the input "in" of "len_bits" bits (a whole number of 16-byte
// blocks) under AES-128 in GCM mode: each block is encrypted in counter mode
// using the counter block "ivec" and the AES round keys "key", the result is
// written to "out", and the running GHASH authenticator "tag" is updated using
// the precomputed table of H-powers "Htable". On return the updated counter is
// written back to "ivec", the updated authenticator to "tag", and the number
// of bytes processed is returned.

// Standard ARM ABI: X0 = in, X1 = len_bits, X2 = out, X3 = tag, X4 = ivec,
// X5 = key, X6 = Htable, returns X0
// ----------------------------------------------------------------------------

// Origin: Hanno Becker's 'clean' AArch64 AES-GCM implementation (derived from
// aesv8-gcm-armv8.pl by Fangming Fang, OpenSSL, and ARM's AArch64cryptolib by
// Samuel Lee), SLOTHY-optimized. The main 4x-unrolled loop is software-pipelined
// by SLOTHY directly from the clean source (the native _swp-style schedule); the
// single-block tail loop is SLOTHY body-only rescheduled (NOT software-pipelined),
// keeping a simple non-pipelined tail. This differs from _swp (whose tail is also
// software-pipelined) only in the tail loop, and from _swp_S (built via the
// de-interleaved route) in the main-loop schedule.

