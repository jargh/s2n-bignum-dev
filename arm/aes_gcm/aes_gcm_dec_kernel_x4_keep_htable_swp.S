    // AARCH64_VALID_CALL_TARGET
        CFI_START
        CFI_DEC_SP(STACK_SIZE)


Ldec_preamble_start:
        save_gprs
        save_vregs

        lsr byte_len, len_bits, #3

        load_round_keys
        load_tag
        load_iv

        prepare_loop_counts
        prepare_ghash

        load_htable_34
        load_htable_12

Ldec_preamble_end:

        cbz count, Lloop_unrolled_end
        cmp count, #1
        b.eq Lloop_unrolled_start_iter_1
        rev32 v8.16B, v31.16B
        aesr v8.16b, v18.16b
