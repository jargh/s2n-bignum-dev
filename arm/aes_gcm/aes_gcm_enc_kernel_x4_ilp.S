        .align        4
S2N_BN_SYMBOL(aes_gcm_enc_kernel_x4_ilp):

    // AARCH64_VALID_CALL_TARGET
        CFI_START
        CFI_DEC_SP(STACK_SIZE)


Lenc_preamble_start:
        save_gprs
        save_vregs

        lsr byte_len, len_bits, #3

        load_round_keys
        load_full_htable
        load_tag
        load_iv

        prepare_loop_counts
        prepare_ghash

Lenc_preamble_end:

        cbz count, Lloop_unrolled_end
Lloop_unrolled_start:
                                                 // Instructions:    115
                                                 // Expected cycles: 71
                                                 // Expected IPC:    1.62

                                                 // Cycle bound:     71.0
                                                 // IPC bound:       1.62

                                                 // Wall time:     43.24s
                                                 // User time:     43.24s

                                                 // -------------------------- cycle (expected) -------------------------->
                                                 // 0                        25                       50
                                                 // |------------------------|------------------------|--------------------
        rev32 v9.16B, v31.16B                    // *......................................................................
        add v1.4S, v31.4S, v30.4S                // *......................................................................
