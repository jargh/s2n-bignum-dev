// ----------------------------------------------------------------------------
// AES-GCM encryption kernel (AES-128), SWP main loop + simple tail, schedule variant 5: x4_scalar_iv_mem_late_tag_scalar_rk_swp_alt5
// Encrypts the input in CTR mode while accumulating the GHASH of the output.

// extern uint64_t aes_gcm_enc_kernel_x4_scalar_iv_mem_late_tag_scalar_rk(const uint8_t *in, uint64_t len_bits,
// uint8_t *out, uint64_t *tag,
// const uint8_t *ivec,
// const s2n_bignum_AES_KEY *key,
// const uint64_t *Htable);

// Processes the input "in" of "len_bits" bits (a whole number of 16-byte
// blocks) under AES-128 in GCM mode: each block is encrypted in counter mode
// using the counter block "ivec" and the AES round keys "key", the result is
// written to "out", and the running GHASH authenticator "tag" is updated using
// the precomputed table of H-powers "Htable". On return the updated counter is
// written back to "ivec", the updated authenticator to "tag", and the number
// of bytes processed is returned.

// Standard ARM ABI: X0 = in, X1 = len_bits, X2 = out, X3 = tag, X4 = ivec,
// X5 = key, X6 = Htable, returns X0
// ----------------------------------------------------------------------------

// Origin: this is a 'clean' (unoptimized, readability-oriented) AArch64 AES-GCM
// implementation by Hanno Becker, derived from the assembly generated by
// aesv8-gcm-armv8.pl (Fangming Fang, OpenSSL) and ultimately from ARM's
// AArch64cryptolib (Samuel Lee). It is intended as input to formal verification
// and to the SLOTHY superoptimizer. Here it is reproduced essentially verbatim,
// with only the surrounding assembler boilerplate replaced by the s2n-bignum
// house style.

