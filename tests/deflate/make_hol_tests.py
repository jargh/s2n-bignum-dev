# Generate hol_tests.ml: small DEFLATE streams of each kind, with the output
# and byte count that zlib gives, for checking with DEFLATE_DECODE_RULE.
# usage: python3 -I make_hol_tests.py > hol_tests.ml
import os, random, sys, zlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rfc1951_ref as ref

rng = random.Random(7)


def raw(data, level=9, strategy=zlib.Z_DEFAULT_STRATEGY, flushes=()):
    c = zlib.compressobj(level, zlib.DEFLATED, -15, 9, strategy)
    out, pos = b'', 0
    for at, kind in flushes:
        out += c.compress(data[pos:at]) + c.flush(kind)
        pos = at
    return out + c.compress(data[pos:]) + c.flush(zlib.Z_FINISH)


def btypes(stream):
    """The block types of a stream, by decoding with the mirror's parts."""
    kinds, p, out = [], 0, []
    while True:
        final, bt = ref.bit(stream, p), ref.bits(stream, p + 1, 2)
        kinds.append(bt)
        p = ref.deflate_block(stream, bt, out, p + 3)
        if final:
            return kinds


text = (b'The DEFLATE format: blocks of literals and length/distance pairs, '
        b'coded with fixed or dynamic Huffman codes, or stored. ' * 2)
cases = [
    ('fixed a', raw(b'a')),
    ('fixed abc', raw(b'abcabcabcabc', strategy=zlib.Z_FIXED)),
    ('stored', raw(b'hello, world', level=0)),
    ('empty', raw(b'')),
    ('dynamic text', raw(text)),
    ('dynamic rle', raw(b'aaaaaaaaaabbbbbbbbbbbaaaaaaaaaaaacccccccc' * 3,
                        strategy=zlib.Z_RLE)),
    ('huffman only', raw(bytes(rng.randrange(8) for _ in range(120)),
                         strategy=zlib.Z_HUFFMAN_ONLY)),
    ('sync flush', raw(b'abcdefabcdef' * 3,
                       flushes=[(18, zlib.Z_SYNC_FLUSH)])),
    ('full flush fixed', raw(b'xyzxyzxyz' * 4, strategy=zlib.Z_FIXED,
                             flushes=[(9, zlib.Z_FULL_FLUSH)])),
    ('long distance', raw(bytes(rng.randrange(256) for _ in range(300)) +
                          b'0123456789' * 2 + bytes(range(256)) * 0 +
                          bytes(rng.randrange(256) for _ in range(40)))),
]

# Crafted streams with a single distance code and with no distance codes.
import craft
for want in ['single distance code', 'no distance codes',
             'single literal/length code']:
    craft.rng.seed(11)
    for _ in range(20000):
        s = craft.stream()
        r = ref.decode(s)
        if r and want in ref.FEATURES and len(s) < 120 and len(r[0]) < 200:
            cases.append(('crafted ' + want, s))
            break

print('needs "tests/deflate/rfc1951_eval.ml";;')
print()
print('(* Generated by make_hol_tests.py: name, input, expected output and *)')
print('(* number of bytes used, as given by zlib.                          *)')
print()
print('let hol_tests = [')
lines = []
for name, s in cases:
    d = zlib.decompressobj(-15)
    out = d.decompress(s)
    assert d.eof
    n = len(s) - len(d.unused_data)
    assert ref.decode(s) == (out, n), name
    lines.append('  ("%s", [%s],\n   [%s], %d)' % (
        name + ' ' + str(btypes(s)), '; '.join(map(str, s)),
        '; '.join(map(str, out)), n))
print(';\n'.join(lines) + '];;')
